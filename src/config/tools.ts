/**
 * Curated list of featured tool IDs / slugs displayed in the homepage Popular Tools section.
 * Configured as a deterministic selection of 8 prominent tools across diverse categories.
 * Can easily be modified by administrators/developers to change featured tools.
 */
export const HOMEPAGE_POPULAR_TOOL_SLUGS = [
  "image-compressor",
  "merge-pdf",
  "qr-code-generator",
  "json-formatter",
  "word-counter",
  "password-generator",
  "image-to-pdf",
  "percentage-calculator",
] as const;

/**
 * Returns the curated popular tools for the homepage.
 * Resolves each slug against the existing TOOL_MAP to guarantee authentic metadata,
 * removes any duplicates, and ensures only valid registered tools are returned.
 */
export const getHomepagePopularTools = (): ToolMeta[] => {
  const seen = new Set<string>();
  const tools: ToolMeta[] = [];

  for (const slugOrId of HOMEPAGE_POPULAR_TOOL_SLUGS) {
    if (seen.has(slugOrId)) continue;
    const tool = TOOL_MAP.get(slugOrId) || TOOLS.find((t) => t.id === slugOrId);
    if (tool && !seen.has(tool.id)) {
      seen.add(tool.id);
      seen.add(tool.slug);
      tools.push(tool);
    }
  }

  return tools;
};

export const getRelatedTools = (slug: string) => {
  const tool = TOOL_MAP.get(slug);
  if (!tool) return [];
  return tool.relatedTools
    .map((s) => TOOL_MAP.get(s))
    .filter((t): t is ToolMeta => t !== undefined);
};

